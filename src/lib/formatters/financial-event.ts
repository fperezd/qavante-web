/** Traduce códigos del contrato y nunca deja caer un código desconocido a la interfaz. */
export function financialEventLabel(value: string | null | undefined): string | null {
  const normalized = value?.trim();
  if (!normalized) return null;

  const known = FINANCIAL_EVENT_LABELS[normalized.toLowerCase()];
  if (known) return known;

  return /^[a-z0-9_.:-]+$/i.test(normalized) ? "Tipo de movimiento no identificado" : normalized;
}
